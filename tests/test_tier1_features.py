class TestFeature1FastModeCLI(unittest.TestCase):
    """Feature 1: Fast Mode CLI Invocation (--fast)."""

    def setUp(self):
        if not is_fast_mode_supported():
            self.skipTest("Feature 1: --fast CLI flag pending implementation in Milestone 1")

    def test_f1_01_cli_fast_flag_recognized(self):
        """CLI recognizes --fast without throwing unrecognized argument error."""
        res = run_cli(["--fast"], timeout=10.0)
        self.assertNotIn("unrecognized arguments", res.stderr.lower())

    def test_f1_02_fast_mode_exit_code_zero(self):
        """Fast mode CLI command exits with return code 0."""
        res = run_cli(["--fast"], timeout=10.0)
        self.assertEqual(res.returncode, 0, f"CLI exited with {res.returncode}: {res.stderr}")

    def test_f1_03_fast_mode_no_playwright_overhead(self):
        """Fast mode executes without launching Playwright or creating screenshots."""
        screenshots_dir = PROJECT_ROOT / "free_dashboard_screenshots"
        mtime_before = {}
        if screenshots_dir.exists():
            for p in screenshots_dir.glob("*.png"):
                mtime_before[p.name] = p.stat().st_mtime

        res = run_cli(["--fast"], timeout=10.0)
        self.assertEqual(res.returncode, 0)

        # No new screenshots should have been modified during fast run
        if screenshots_dir.exists():
            for p in screenshots_dir.glob("*.png"):
                if p.name in mtime_before:
                    self.assertEqual(
                        mtime_before[p.name],
                        p.stat().st_mtime,
                        f"Screenshot {p.name} was modified during --fast run!"
                    )

    def test_f1_04_fast_mode_produces_terminal_output(self):
        """Fast mode terminal stdout contains expected summary sections."""
        res = run_cli(["--fast"], timeout=10.0)
        stdout = res.stdout.upper()
        self.assertTrue(
            "FAST" in stdout or "MOMENTUM" in stdout or "QUANT BIAS" in stdout,
            f"Expected momentum/quant headers in stdout: {res.stdout[:400]}"
        )

    def test_f1_05_fast_mode_updates_snapshot_file(self):
        """Fast mode execution writes updated market_snapshot.json."""
        snapshot_path = PROJECT_ROOT / "market_snapshot.json"
        time_before = time.time() - 2.0
        res = run_cli(["--fast"], timeout=10.0)
        self.assertEqual(res.returncode, 0)
        self.assertTrue(snapshot_path.exists())
        self.assertGreaterEqual(snapshot_path.stat().st_mtime, time_before)


