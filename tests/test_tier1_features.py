class TestFeature4DynamicATRRiskModel(unittest.TestCase):
    """Feature 4: Dynamic ATR Risk Model (SL, TP 1:2, TP 1:3)."""

    def test_f4_01_atr_risk_long_scenario_math(self):
        """Long scenario: SL = P - 1.5*ATR, TP1 = P + 3*ATR, TP2 = P + 4.5*ATR."""
        price, atr = 80000.0, 1000.0
        ref = reference_atr_risk_levels(price, atr, quant_bias_score=20)
        long_data = ref["long"]
        self.assertEqual(long_data["stop_loss"], 78500.0)      # 80000 - 1500
        self.assertEqual(long_data["tp1_rr2"], 83000.0)       # 80000 + 3000 (1:2 R:R)
        self.assertEqual(long_data["tp2_rr3"], 84500.0)       # 80000 + 4500 (1:3 R:R)
        self.assertEqual(long_data["risk_usd"], 1500.0)
        self.assertAlmostEqual(long_data["risk_pct"], 1.875, places=3)

    def test_f4_02_atr_risk_short_scenario_math(self):
        """Short scenario: SL = P + 1.5*ATR, TP1 = P - 3*ATR, TP2 = P - 4.5*ATR."""
        price, atr = 80000.0, 1000.0
        ref = reference_atr_risk_levels(price, atr, quant_bias_score=-20)
        short_data = ref["short"]
        self.assertEqual(short_data["stop_loss"], 81500.0)     # 80000 + 1500
        self.assertEqual(short_data["tp1_rr2"], 77000.0)      # 80000 - 3000 (1:2 R:R)
        self.assertEqual(short_data["tp2_rr3"], 75500.0)      # 80000 - 4500 (1:3 R:R)
        self.assertEqual(short_data["risk_usd"], 1500.0)
        self.assertAlmostEqual(short_data["risk_pct"], 1.875, places=3)

    def test_f4_03_atr_risk_recommendation_directional_mapping(self):
        """Recommendation maps to LONG for score>=15, SHORT for score<=-15, NEUTRAL otherwise."""
        price, atr = 83000.0, 450.0
        bull = reference_atr_risk_levels(price, atr, quant_bias_score=25)
        self.assertEqual(bull["direction"], "LONG")
        self.assertEqual(bull["recommended"]["scenario"], "LONG")

        bear = reference_atr_risk_levels(price, atr, quant_bias_score=-30)
        self.assertEqual(bear["direction"], "SHORT")
        self.assertEqual(bear["recommended"]["scenario"], "SHORT")

        neut = reference_atr_risk_levels(price, atr, quant_bias_score=5)
        self.assertEqual(neut["direction"], "NEUTRAL")
        self.assertEqual(neut["recommended"]["scenario"], "NEUTRAL")

    def test_f4_04_atr_risk_function_contract_in_module(self):
        """calculate_atr_risk_levels matches PROJECT.md interface contract schema."""
        if not is_atr_risk_implemented():
            self.skipTest("calculate_atr_risk_levels pending implementation in Milestone 1")
        res = bmi.calculate_atr_risk_levels(83000.0, 450.0, 20)
        self.assertIsInstance(res, dict)
        self.assertIn("atr14", res)
        self.assertIn("buffer", res)
        self.assertIn("direction", res)
        self.assertIn("long", res)
        self.assertIn("short", res)
        self.assertIn("recommended", res)
        self.assertIn("stop_loss", res["long"])
        self.assertIn("tp1_rr2", res["long"])
        self.assertIn("tp2_rr3", res["long"])

    def test_f4_05_atr_risk_realistic_market_example(self):
        """Verify exact values for BTC ~$83,056.16 and ATR4H $476.16 from explorer survey."""
        price = 83056.16
        atr = 476.16
        res = reference_atr_risk_levels(price, atr, quant_bias_score=32)
        # 1.5 * 476.16 = 714.24
        self.assertEqual(res["buffer"], 714.24)
        self.assertEqual(res["long"]["stop_loss"], 82341.92)
        self.assertEqual(res["long"]["tp1_rr2"], 84484.64)
        self.assertEqual(res["long"]["tp2_rr3"], 85198.88)


class TestFeature5WinrateCalibrationTracker(unittest.TestCase):
    """Feature 5: Winrate Calibration Tracker."""

    def test_f5_01_tracker_file_schema_and_keys(self):
        """Calibration tracker file is valid JSON list of signal records."""
        tracker_path = PROJECT_ROOT / "quant_calibration_tracker.json"
        self.assertTrue(tracker_path.exists())
        data = json.loads(tracker_path.read_text(encoding="utf-8"))
        self.assertIsInstance(data, list)
        if len(data) > 0:
            rec = data[0]
            self.assertIn("id", rec)
            self.assertIn("timestamp_utc", rec)
            self.assertIn("quant_bias_score", rec)
            self.assertIn("resolved", rec)

    def test_f5_02_tracker_signal_logging(self):
        """Tracker update function records current snapshot telemetry."""
        snap = make_mock_snapshot()
        test_path = PROJECT_ROOT / "_test_tier1_tracker.json.tmp"
        try:
            res = bmi.update_calibration_tracker(snap, tracker_path=test_path)
            self.assertIsInstance(res, dict)
            self.assertIn("total_signals_tracked", res)
            self.assertGreaterEqual(res["total_signals_tracked"], 1)
        finally:
            if test_path.exists():
                test_path.unlink()

    def test_f5_03_tracker_resolution_long_win(self):
        """Long signal resolves to WIN when price increases over 24h."""
        test_path = PROJECT_ROOT / "_test_tier1_tracker_win.json.tmp"
        try:
            t0 = time.time() - 30 * 3600
            snap1 = {
                "prices": {"spot_last": 80000.0},
                "quant_bias": {"composite_score": 25, "bias_label": "BULLISH"},
                "divergence_engine": {"24h_divergence": {"divergence_state": "Neutral"}},
                "statistical_z_scores": {"oi_zscore": 0.0},
            }
            bmi.update_calibration_tracker(snap1, tracker_path=test_path, force_time=t0)
            
            # Resolve at higher price (+2%)
            t1 = t0 + 25 * 3600
            snap2 = {
                "prices": {"spot_last": 81600.0},
                "quant_bias": {"composite_score": 20, "bias_label": "BULLISH"},
                "divergence_engine": {"24h_divergence": {"divergence_state": "Neutral"}},
                "statistical_z_scores": {"oi_zscore": 0.0},
            }
            res = bmi.update_calibration_tracker(snap2, tracker_path=test_path, force_time=t1)
            self.assertEqual(res["resolved_signals_count"], 1)
            self.assertEqual(res["wins_total"], 1)
        finally:
            if test_path.exists():
                test_path.unlink()

    def test_f5_04_tracker_resolution_long_loss(self):
        """Long signal resolves to LOSS when price falls over 24h."""
        test_path = PROJECT_ROOT / "_test_tier1_tracker_loss.json.tmp"
        try:
            t0 = time.time() - 30 * 3600
            snap1 = {
                "prices": {"spot_last": 80000.0},
                "quant_bias": {"composite_score": 25, "bias_label": "BULLISH"},
                "divergence_engine": {"24h_divergence": {"divergence_state": "Neutral"}},
                "statistical_z_scores": {"oi_zscore": 0.0},
            }
            bmi.update_calibration_tracker(snap1, tracker_path=test_path, force_time=t0)
            
            # Resolve at lower price (-2%)
            t1 = t0 + 25 * 3600
            snap2 = {
                "prices": {"spot_last": 78400.0},
                "quant_bias": {"composite_score": -10, "bias_label": "NEUTRAL"},
                "divergence_engine": {"24h_divergence": {"divergence_state": "Neutral"}},
                "statistical_z_scores": {"oi_zscore": 0.0},
            }
            res = bmi.update_calibration_tracker(snap2, tracker_path=test_path, force_time=t1)
            self.assertEqual(res["resolved_signals_count"], 1)
            self.assertEqual(res["wins_total"], 0)
        finally:
            if test_path.exists():
                test_path.unlink()

    def test_f5_05_tracker_winrate_metrics_calculation(self):
        """Winrate percentage calculation correctly calculates (wins / total_resolved) * 100."""
        # 1 win out of 1 resolved = 100.0%
        mock_records = make_mock_tracker()
        resolved = [r for r in mock_records if r.get("resolved")]
        wins = [r for r in resolved if r.get("is_win") or r.get("outcome") == "WIN"]
        winrate = (len(wins) / len(resolved)) * 100.0 if resolved else 0.0
        self.assertEqual(winrate, 100.0)


